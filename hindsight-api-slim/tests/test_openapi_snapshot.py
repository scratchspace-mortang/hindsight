"""The committed OpenAPI snapshot must carry the live staleness contract.

``hindsight-docs/static/openapi.json`` is the single source the client
generators and the docs build read; regenerating it is a manual step
(``scripts/generate-openapi.sh``), so a code change can land with the
snapshot still describing the old API and repo CI only notices at
verify-generated-files time. This test compares the live ``app.openapi()``
against the committed snapshot for the properties the staleness change
touched — ``staleness_check`` and ``graph_stale`` on both
``MentalModelTrigger`` shapes, and the ``is_stale`` / ``last_memory_write_at``
descriptions — so the next omission fails here instead of in CI.
"""

import json
from pathlib import Path
from types import SimpleNamespace

from hindsight_api.api import create_app

_SNAPSHOT = Path(__file__).resolve().parents[2] / "hindsight-docs" / "static" / "openapi.json"
_BANK_TEMPLATE_SNAPSHOT = Path(__file__).resolve().parents[2] / "hindsight-docs" / "static" / "bank-template-schema.json"


def _schemas(spec: dict) -> dict:
    return spec["components"]["schemas"]


def test_snapshot_carries_trigger_staleness_fields():
    """MentalModelTrigger Input and Output both publish staleness_check and
    graph_stale with the same enum, default and description as live."""
    live = create_app(SimpleNamespace(audit_logger=None), initialize_memory=False).openapi()
    committed = json.loads(_SNAPSHOT.read_text())

    for shape in ("MentalModelTrigger-Input", "MentalModelTrigger-Output"):
        for field in ("staleness_check", "graph_stale"):
            assert _schemas(committed)[shape]["properties"][field] == _schemas(live)[shape]["properties"][field], (
                f"committed {shape}.{field} differs from live — regenerate the snapshot (scripts/generate-openapi.sh)"
            )


def test_snapshot_carries_staleness_descriptions():
    """The is_stale and last_memory_write_at descriptions in the committed
    snapshot match live, so the delivered reference text keeps the graph
    clause and the cited-deletion exception."""
    live = create_app(SimpleNamespace(audit_logger=None), initialize_memory=False).openapi()
    committed = json.loads(_SNAPSHOT.read_text())

    for schema, field in (
        ("MentalModelResponse", "is_stale"),
        ("BankStatsResponse", "last_memory_write_at"),
    ):
        assert _schemas(committed)[schema]["properties"][field] == _schemas(live)[schema]["properties"][field], (
            f"committed {schema}.{field} differs from live — regenerate the snapshot (scripts/generate-openapi.sh)"
        )


def test_bank_template_schema_equals_live_model_schema():
    """The committed bank-template JSON Schema equals
    ``BankTemplateManifest.model_json_schema()`` — the static file is
    regenerated by ``scripts/generate-bank-template-schema.sh``, so a code
    change that adds a trigger field must land with the file regenerated
    instead of failing CI's verify-generated-files job."""
    from hindsight_api.api.http import BankTemplateManifest

    live = BankTemplateManifest.model_json_schema()
    committed = json.loads(_BANK_TEMPLATE_SNAPSHOT.read_text())
    assert committed == live, (
        "committed bank-template-schema.json differs from live — regenerate it (scripts/generate-bank-template-schema.sh)"
    )
